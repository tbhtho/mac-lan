// Package identity is a bounded build marker, NOT proof of authenticity.
// Download signatures and digests are always verified separately.
func ReadPackageIdentity(path string) (Marker, error) {
	var m Marker
	f, err := os.Open(path)
	if err != nil {
		return m, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return m, err
	}
	if !info.Mode().IsRegular() || info.Size() < 14 {
		return m, errors.New("not a standalone MAC-DOW executable")
	}
	tail := make([]byte, 12)
	if _, err = f.ReadAt(tail, info.Size()-12); err != nil {
		return m, err
	}
	size := int64(binary.LittleEndian.Uint32(tail[:4]))
	if string(tail[4:]) != "MCDOWPK1" || size < 2 || size > 4096 || size > info.Size()-14 {
		return m, errors.New("missing standalone package identity")
	}
	head := make([]byte, 2)
	if _, err = f.ReadAt(head, 0); err != nil || string(head) != "MZ" {
		return m, errors.New("not a Windows executable")
	}
	b := make([]byte, size)
	if _, err = f.ReadAt(b, info.Size()-12-size); err != nil {
		return m, err
	}
	if err = json.Unmarshal(b, &m); err != nil {
		return m, err
	}
	if m.Layout != "single-exe" {
		return m, errors.New("unknown standalone layout")
	}
	return m, nil
}
func standalonePlan(p Plan) bool { return p.OS == "windows" && p.Asset.Name == "MAC-DOW.exe" }
func commandlinePreviewPlan(p Plan) bool {
	return p.OS == "darwin" && p.Asset.Name == "MAC-DOW-macos-arm64-commandline-preview.tar.gz"
}

// A preview is a dedicated package directory, never the surrounding Downloads
// folder. Refuse extra files instead of moving a user's neighbors into backup.
func validatePreviewDirectory(root string, installed bool) error {
	allowed := map[string]bool{
		"MacDowHost": true, "MAC-DOW-INSTALL.json": true, "COMMIT.txt": true,
		"README.md": true, "LICENSE": true, "THIRD_PARTY_NOTICES.md": true,
		"BUILD-PROVENANCE.json": true,
		"licenses":              true, "licenses/zeroconf-LICENSE.txt": true,
		"licenses/webview2-NOTICE.txt": true, "licenses/webview2-LICENSE.txt": true,
		"licenses/miekg-dns-LICENSE.txt": true, "licenses/gorilla-websocket.txt": true,
		"licenses/golang-x-LICENSE.txt": true, "licenses/go-LICENSE.txt": true,
	}
	return filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if path == root {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if installed && rel == ".DS_Store" {
			info, err := entry.Info()
			if err != nil || !info.Mode().IsRegular() || info.Size() > 1<<20 {
				return errors.New("unsafe Finder metadata in Mac preview")
			}
			// Finder metadata is retained in the rollback backup and can be
			// regenerated by Finder. It never authorizes another neighbor.
			return nil
		}
		if !allowed[rel] || entry.Type()&os.ModeSymlink != 0 || (entry.IsDir() != (rel == "licenses")) {
			return errors.New("Mac preview contains unrelated files or unsupported links; keep MAC-DOW in its own extracted package folder")
		}
		info, err := entry.Info()
		if err != nil || (!info.IsDir() && !info.Mode().IsRegular()) {
			return errors.New("non-regular Mac preview file")
		}
		return nil
	})
}

func rejectBroadPreviewDirectory(root string) error {
	if home, err := os.UserHomeDir(); err == nil {
		for _, name := range []string{"", "Downloads", "Desktop", "Documents", "Movies", "Pictures", "Music", "Public", "Applications", "Library"} {
			if root == filepath.Join(home, name) {
				return errors.New("Mac preview must have its own package folder, not a home or user-content folder")
			}
		}
	}
	if root == "/Applications" || root == "/Library" || root == "/System" || root == "/Users" {
		return errors.New("cannot replace a shared system folder with a Mac preview")
	}
	return nil
}

// Signed release metadata supplies authenticity; this shape check prevents a
// package for another executable format/architecture being installed as a host.
func validateMacHost(path string, requireExecutable bool) error {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Size() < 32 || (requireExecutable && info.Mode().Perm()&0111 == 0) {
		return errors.New("missing executable Apple Silicon host")
	}
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	var header [16]byte
	if _, err = io.ReadFull(f, header[:]); err != nil {
		return err
	}
	if binary.LittleEndian.Uint32(header[:4]) != 0xfeedfacf || binary.LittleEndian.Uint32(header[4:8]) != 0x0100000c || binary.LittleEndian.Uint32(header[12:16]) != 2 {
		return errors.New("host is not an arm64 Mach-O executable")
	}
	return nil
}
func appBundle(base string) string { return filepath.Join(base, "MAC-DOW Host.app") }
func isApp(path string) bool       { return strings.HasSuffix(path, ".app") }
func metadataRoot(root string) string {
	if isApp(root) {
		return filepath.Join(root, "Contents", "Resources")
	}
	return root
}
func copyStandalone(src *os.File, dest string) error {
	out, err := os.OpenFile(filepath.Join(dest, "MAC-DOW.exe"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0700)
	if err != nil {
		return err
	}
	if _, err = src.Seek(0, io.SeekStart); err == nil {
		_, err = io.Copy(out, src)
	}
	closeErr := out.Close()
	if err != nil {
		return err
	}
	return closeErr
}

func compatibleInstallShape(install, next, goos string) error {
	before, err := os.Stat(install)
	if err != nil {
		return err
	}
	after, err := os.Stat(next)
	if err != nil {
		return err
	}
	if before.IsDir() != after.IsDir() || (goos == "darwin" && isApp(install) != isApp(next)) {
		return errors.New("this older installation uses a different package layout; move to the standalone app once before in-app replacement")
	}
	return nil
}
